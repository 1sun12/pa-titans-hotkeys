"""Render uikeys.txt + game_defaults.json into a readable KEYS.md and BUILD_GRID.md."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SLOTS = "ZXCVASDFQWER"  # grid key for slot 1..12: row 1 Z X C V, row 2 A S D F, row 3 Q W E R
CATS = {"1": "Z Economy", "2": "X Combat", "3": "C Utility", "4": "V Build"}


def parse(binds):
    """[(keyset, action)] -> {action: 'key, key'} keeping file order."""
    out = {}
    for k, a in binds:
        k = re.sub(r"sc_([a-z])\b", lambda m: m[1].upper(), k).replace("sc_", "")
        out[a] = f"{out[a]}, {k}" if a in out else k
    return out


def main():
    g = json.load(open(f"{HERE}/game_defaults.json"))
    lines = [l.rstrip("\n").split(None, 2)[1:] for l in open(f"{HERE}/uikeys.txt") if l.startswith("bind ")]
    cur = parse(lines)
    dft = parse((b["keyset"], b["action"]) for b in g["default_binds"])
    name = lambda u: g["names"].get(u, u)

    md = ["# BAR hotkeys", "", "Generated by `render.py` from `uikeys.txt`. Do not edit by hand.", "",
          f"Game build: {g['game']}. Active profile: **{g['active_profile']}**, compared against the shipped "
          f"**{g['profile']}** profile. *changed* marks actions whose keys differ; empty means unbound.", "",
          "Letter keys are scancodes (physical position, same on any layout). `Any+` fires whatever modifiers "
          "are held. `a,b` is a chain: press a then b. Space is the Meta key.", ""]
    seen = set()

    def row(action, label):
        seen.add(action)
        c, d = cur.get(action, ""), dft.get(action, "")
        mark = " *changed*" if c != d else ""
        return f"| {label} | `{action}` | {d} | {c}{mark} |"

    for cat in g["categories"]:
        md += [f"## {cat['name']}", "", "| Action | Command | Default | Current |", "|---|---|---|---|"]
        for it in cat["items"]:
            if "action" in it:
                md.append(row(it["action"], it["label"]))
                continue
            p = it["prefix"]
            members = [p + m for m in it.get("members", [])]
            for a in members + sorted(a for a in {*cur, *dft} - set(members) if a.startswith(p) and a not in seen):
                n = a[len(p):]
                lbl = name(n) if it.get("unit") else (it["label"] or a)
                lbl = lbl.replace("%{n}", n).replace("%{unit}", name(n))
                if "%{row}" in lbl:
                    r, c = n.split()
                    lbl = lbl.replace("%{row}", r).replace("%{col}", c)
                md.append(row(a, lbl))
        md.append("")
    for title, acts in (("Hidden (chat, text editing, quit)", g["hidden"]),
                        ("Other (bound, not in the game's catalog)", sorted({*cur, *dft} - seen - set(g["hidden"])))):
        if not acts:
            continue
        md += [f"## {title}", "", "| Action | Command | Default | Current |", "|---|---|---|---|"]
        md += [row(a, "") for a in acts] + [""]
    open(f"{HERE}/KEYS.md", "w").write("\n".join(md))

    order = lambda u: (re.sub(r"^(arm|cor|leg)", "", u), u)
    head = "| " + " | ".join(SLOTS) + " |"
    grid = ["# BAR build grid", "", "Generated by `render.py` from `game_defaults.json`. Do not edit by hand.", "",
            "The grid menu puts every build option on a 3x4 block of keys:", "",
            "```", "Q W E R   row 3", "A S D F   row 2", "Z X C V   row 1", "```", "",
            "Factories show their units straight on the grid; *p2* is the second page (`B` flips pages).",
            "Builders first pick a category (Z Economy, X Combat, C Utility, V Build), then a grid key: "
            "a T1 bot constructor builds a metal extractor with Z then Z.", "",
            "## Factories", "", "| Factory " + head, "|---" * 13 + "|"]
    for lab in sorted(g["labs"], key=order):
        slots = {int(i): u for i, u in g["labs"][lab].items()}
        for page in range(1, (max(slots) - 1) // 12 + 2):
            cells = [name(slots.get((page - 1) * 12 + s, "")) for s in range(1, 13)]
            grid.append(f"| {name(lab)} `{lab}`{' *p2*' if page > 1 else ''} | " + " | ".join(cells) + " |")
    grid += ["", "## Builders", "", "| Builder | Category " + head, "|---" * 14 + "|"]
    for b in sorted(g["builders"], key=order):
        for c in "1234":
            cells = [name(g["builders"][b].get(f"{c}.{(s - 1) // 4 + 1}.{(s - 1) % 4 + 1}", "")) for s in range(1, 13)]
            if any(cells):
                grid.append(f"| {name(b)} `{b}` | {CATS[c]} | " + " | ".join(cells) + " |")
    open(f"{HERE}/BUILD_GRID.md", "w").write("\n".join(grid) + "\n")
    print(f"KEYS.md: {len(cur)} bound actions; BUILD_GRID.md: {len(g['labs'])} factories, {len(g['builders'])} builders")


if __name__ == "__main__":
    main()
