"""Render hotbuild2_layout.pas + game_default_keys.json into a readable KEYS.md."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
short = lambda u: u["json"].split("/")[-1].removesuffix(".json")


def main():
    layout = json.load(open(f"{HERE}/hotbuild2_layout.pas"))
    defaults = json.load(open(f"{HERE}/game_default_keys.json"))
    keys, slots = layout["hotbuildglobalkey"], layout["hotbuildglobal"]
    lines = ["# PA Titans hotkeys", "", "Generated by `render.py` from `hotbuild2_layout.pas`. Do not edit by hand.", "",
             "## Hotbuild2 keys", "", "Units cycle in this order on repeated presses.", "",
             "| Key | Slot | Units |", "|---|---|---|"]
    for slot in sorted(slots, key=lambda s: keys.get(s, "~")):
        lines.append(f"| **{keys.get(slot, '(unbound)').upper()}** | {slot} | {', '.join(map(short, slots[slot]))} |")
    lines += ["", "## Game keybinds", "", "Current value comes from the game's saved settings; "
              "*changed* marks binds that differ from the game default. Empty means unbound.", "",
              "| Group | Sub group | Action | Default | Current |", "|---|---|---|---|---|"]
    cur = {u["key"]: u["value"] for u in layout["uber"]}
    for k, d in defaults.items():
        c = cur.get(k, d["default"])
        mark = " *changed*" if c != d["default"] else ""
        lines.append(f"| {d['group']} | {d['sub_group']} | {k} | {d['default']} | {c}{mark} |")
    for k in cur.keys() - defaults.keys():
        lines.append(f"| (mod) | | {k} | | {cur[k]} |")
    open(f"{HERE}/KEYS.md", "w").write("\n".join(lines) + "\n")
    print(f"KEYS.md: {len(slots)} hotbuild slots, {len(cur)} game binds")


if __name__ == "__main__":
    main()
